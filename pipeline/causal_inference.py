    @torch.no_grad()
    def particle_update(
        self,
        x_latent_list,          # list[Tensor]
        y_pred_pixel_list,      # list[Tensor]
        y_obs_pixel,            # Tensor
        guidance_scale: float = 1.0,
        eps: float = 1e-8,
    ):
        assert len(x_latent_list) == len(y_pred_pixel_list), "latent list and pixel pred list must match"
        P = len(x_latent_list)
        assert P > 0

        # Preserve original dtypes/devices
        # x0 = x_latent_list[0]
        # orig_dtype = x0.dtype
        # device = x0.device

        # Stack (keep original dtype for storage)
        X = torch.stack(x_latent_list, dim=0)       # (P, ...)
        Y = torch.stack(y_pred_pixel_list, dim=0)   # (P, ...)

        # Broadcast observation to particle dimension
        y_obs = y_obs_pixel.unsqueeze(0).expand_as(Y)  # (P, ...)

        # # --- Compute in float32 for numerical stability / dtype compatibility ---
        # Xf = X.float()
        # Yf = Y.float()
        # y_obs_f = y_obs.float()

        # Ensemble mean / diffs
        X_mean = X.mean(dim=0, keepdim=True)
        Y_mean = Y.mean(dim=0, keepdim=True)

        Xs_diff = X - X_mean                           # (P, ...)
        Ys_diff = Y - Y_mean                           # (P, ...)

        # L2 grad for 0.5 * ||Y - y_obs||^2  => (Y - y_obs)
        Ys_err = (Y - y_obs)                         # (P, ...)

        # Flatten per-particle
        Xs_diff_f = Xs_diff.reshape(P, -1)              # (P, Dx)
        Ys_diff_f = Ys_diff.reshape(P, -1)              # (P, Dy)
        Ys_err_f  = Ys_err.reshape(P, -1)               # (P, Dy)

        # (P,P)
        coef = (Ys_err_f @ Ys_diff_f.T) / P#float(P)
        coef = coef.to(dtype=X.dtype)

        # (P,Dx)
        dxs = coef @ Xs_diff_f

        # step size
        lr = guidance_scale / (torch.linalg.matrix_norm(coef))

        # Update in float32 then cast back
        X_updated = X - lr * dxs.reshape_as(X)
        # X_updated = X_updated.to(dtype=orig_dtype, device=device)

        return [X_updated[p] for p in range(P)]
    
   
    def _initialize_kv_cache(self, batch_size, dtype, device):
        """
        Initialize a Per-GPU KV cache for the Wan model.
        """
        kv_cache1 = []
        if self.local_attn_size != -1:
            # Use the local attention size to compute the KV cache size
            kv_cache_size = self.local_attn_size * self.frame_seq_length
        else:
            # Use the default KV cache size
            kv_cache_size = 32760

        for _ in range(self.num_transformer_blocks):
            kv_cache1.append({
                "k": torch.zeros([batch_size, kv_cache_size, 12, 128], dtype=dtype, device=device),
                "v": torch.zeros([batch_size, kv_cache_size, 12, 128], dtype=dtype, device=device),
                "global_end_index": torch.tensor([0], dtype=torch.long, device=device),
                "local_end_index": torch.tensor([0], dtype=torch.long, device=device)
            })

        self.kv_cache1 = kv_cache1  # always store the clean cache

    def _initialize_crossattn_cache(self, batch_size, dtype, device):
        """
        Initialize a Per-GPU cross-attention cache for the Wan model.
        """
        crossattn_cache = []

        for _ in range(self.num_transformer_blocks):
            crossattn_cache.append({
                "k": torch.zeros([batch_size, 512, 12, 128], dtype=dtype, device=device),
                "v": torch.zeros([batch_size, 512, 12, 128], dtype=dtype, device=device),
                "is_init": False
            })
        self.crossattn_cache = crossattn_cache